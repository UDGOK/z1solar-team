/**
 * Generates FILE-MANIFEST.txt — every source file under a bracket route folder,
 * with its line count.
 *
 * Why this exists: Windows File Explorer's "Extract All" corrupts folder names
 * containing square brackets, dropping files into the wrong directory. It has
 * happened four times on this project. The old guard hard-coded two paths and
 * two line counts, which meant it (a) missed any new bracket route and (b)
 * reported a false failure every time those two files legitimately changed.
 *
 * A generated manifest can't go stale: it is rebuilt whenever the project is
 * packaged, so it always describes the zip it ships inside.
 *
 * Run: node scripts/make-manifest.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "src");
const out = [];

function walk(dir, rel = "") {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    const r = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      walk(full, r);
    } else if (/\.(ts|tsx)$/.test(entry.name) && r.includes("[")) {
      // Count lines the same way both verifiers do: number of newline-separated
      // lines, matching PowerShell's Measure-Object -Line and findstr /R /N.
      const lines = fs.readFileSync(full, "utf8").split("\n");
      if (lines[lines.length - 1] === "") lines.pop();
      out.push(`${lines.length}\tsrc/${r}`);
    }
  }
}

walk(SRC);

const header = [
  "# Z1Power Team Hub — bracket-route file manifest",
  "# Generated by scripts/make-manifest.js. Do not edit by hand.",
  "#",
  "# Each line is: <line count><TAB>src/<path>",
  "# EXTRACT-SAFELY.ps1 and verify-files.bat check every entry after extraction.",
  "# A mismatch means Windows mangled a [bracket] folder — do not build or push.",
  `# ${out.length} files covered.`,
  "",
];

fs.writeFileSync(path.join(ROOT, "FILE-MANIFEST.txt"), header.concat(out).join("\n") + "\n");
console.log(`FILE-MANIFEST.txt written — ${out.length} bracket-route files.`);
out.forEach((l) => console.log("  " + l.replace("\t", " lines\t")));
